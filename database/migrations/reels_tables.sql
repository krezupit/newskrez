CREATE TABLE IF NOT EXISTS `reel_sources` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `name` VARCHAR(100) NOT NULL,
  `code` VARCHAR(50) NOT NULL UNIQUE,
  `source_type` VARCHAR(50) NOT NULL DEFAULT 'youtube_channel',
  `channel_id` VARCHAR(100),
  `playlist_id` VARCHAR(100),
  `feed_url` VARCHAR(500),
  `default_category_slug` VARCHAR(100) DEFAULT 'general-news',
  `is_enabled` BOOLEAN NOT NULL DEFAULT TRUE,
  `requires_editorial_approval` BOOLEAN NOT NULL DEFAULT FALSE,
  `daily_publish_limit` INT DEFAULT 10,
  `published_today` INT NOT NULL DEFAULT 0,
  `last_fetched_at` TIMESTAMP NULL,
  `last_success_at` TIMESTAMP NULL,
  `last_error_message` TEXT NULL,
  `total_reels_imported` INT NOT NULL DEFAULT 0,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_reel_sources_enabled` (`is_enabled`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `reels` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `title` VARCHAR(255) NOT NULL,
  `slug` VARCHAR(255) NOT NULL UNIQUE,
  `description` TEXT NULL,
  `video_url` VARCHAR(500) NOT NULL,
  `video_type` VARCHAR(50) NOT NULL DEFAULT 'youtube',
  `external_id` VARCHAR(191) NULL,
  `thumbnail_url` VARCHAR(500) NULL,
  `duration_seconds` INT DEFAULT 30,
  `aspect_ratio` VARCHAR(20) DEFAULT '9:16',
  `source_id` INT NULL,
  `source_name` VARCHAR(100) NULL,
  `source_url` VARCHAR(500) NULL,
  `channel_title` VARCHAR(150) NULL,
  `primary_category_id` INT NULL,
  `category_slug` VARCHAR(100) DEFAULT 'general-news',
  `category_name` VARCHAR(100) DEFAULT 'General News',
  `related_article_id` INT NULL,
  `status` VARCHAR(30) NOT NULL DEFAULT 'Published',
  `rights_status` VARCHAR(50) DEFAULT 'Authorized Embed',
  `is_featured` BOOLEAN DEFAULT FALSE,
  `views_count` INT NOT NULL DEFAULT 0,
  `likes_count` INT NOT NULL DEFAULT 0,
  `shares_count` INT NOT NULL DEFAULT 0,
  `metadata` TEXT NULL,
  `published_at` TIMESTAMP NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_reels_status` (`status`),
  INDEX `idx_reels_category` (`category_slug`),
  INDEX `idx_reels_external_id` (`external_id`),
  INDEX `idx_reels_published` (`published_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `reel_generation_jobs` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `article_id` INT NULL,
  `title` VARCHAR(255) NOT NULL,
  `summary` TEXT NULL,
  `script_text` TEXT NULL,
  `voice_provider` VARCHAR(50) DEFAULT 'web_speech',
  `voice_id` VARCHAR(100) NULL,
  `audio_url` VARCHAR(500) NULL,
  `video_template` VARCHAR(50) DEFAULT 'vertical_news_v1',
  `status` VARCHAR(30) NOT NULL DEFAULT 'pending',
  `output_video_url` VARCHAR(500) NULL,
  `thumbnail_url` VARCHAR(500) NULL,
  `error_message` TEXT NULL,
  `reel_id` INT NULL,
  `created_by` INT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_reel_jobs_status` (`status`),
  INDEX `idx_reel_jobs_article` (`article_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `reel_views` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `reel_id` INT NOT NULL,
  `ip_address` VARCHAR(100) NULL,
  `user_agent` VARCHAR(255) NULL,
  `watch_duration_seconds` INT DEFAULT 0,
  `completed` BOOLEAN DEFAULT FALSE,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_reel_views_reel` (`reel_id`),
  INDEX `idx_reel_views_date` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `reel_import_logs` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `source_id` INT NULL,
  `source_name` VARCHAR(100) NULL,
  `status` VARCHAR(30) NOT NULL,
  `reels_found` INT NOT NULL DEFAULT 0,
  `reels_imported` INT NOT NULL DEFAULT 0,
  `reels_skipped` INT NOT NULL DEFAULT 0,
  `error_message` TEXT NULL,
  `details` TEXT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_reel_import_source` (`source_id`),
  INDEX `idx_reel_import_status` (`status`),
  INDEX `idx_reel_import_date` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
